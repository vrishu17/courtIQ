"""Idempotent identity bootstrap for a CourtIQ workspace.

Bundles can't manage groups or service principals, so this script is the code
version of that platform layer. Every run compares what exists with what should
exist and changes only the difference, so it is safe to run any number of times.

It checks, and fixes where it can:
  * groups courtiq_admins and courtiq_players exist as ACCOUNT groups. Unity Catalog
    only accepts account groups, and the workspace API can only create workspace-local
    ones, so the script never creates groups: make them in Settings -> Identity and
    access -> Groups -> Add group -> Add new (that creates account groups).
  * service principal courtiq-cicd exists with workspace and SQL access
  * courtiq_admins contains the person running the script and courtiq-cicd
  * courtiq_admins has ALL PRIVILEGES on, and owns, catalogs courtiq_dev and courtiq_prod

It never creates or reads a secret: the principal's OAuth secret is generated by
hand in the workspace UI (Phase 0 guide, Session 2, Step 3).

Usage (PowerShell, from the repo root):
  uv run python bootstrap/02_identity.py --profile courtiq --dry-run
  uv run python bootstrap/02_identity.py --profile courtiq
"""

from __future__ import annotations

import argparse

from databricks.sdk import WorkspaceClient
from databricks.sdk.errors import DatabricksError, NotFound
from databricks.sdk.service import catalog, iam

ADMINS = "courtiq_admins"
PLAYERS = "courtiq_players"
GROUPS = [ADMINS, PLAYERS]
SERVICE_PRINCIPAL = "courtiq-cicd"
SP_ENTITLEMENTS = ["workspace-access", "databricks-sql-access"]
CATALOGS = ["courtiq_dev", "courtiq_prod"]
PATCH_SCHEMA = [iam.PatchSchema.URN_IETF_PARAMS_SCIM_API_MESSAGES_2_0_PATCH_OP]


class Bootstrap:
    def __init__(self, w: WorkspaceClient, dry_run: bool) -> None:
        self.w = w
        self.dry_run = dry_run
        self.problems: list[str] = []

    def log(self, status: str, what: str) -> None:
        prefix = "[dry run] " if self.dry_run and status not in ("ok", "skip") else ""
        print(f"{prefix}{status:<8} {what}")

    def check_group(self, name: str) -> str | None:
        """Return the group's ID if it is an account group; record a problem otherwise."""
        found = list(self.w.groups.list(filter=f'displayName eq "{name}"', attributes="id,meta"))
        if not found:
            self.log("missing", f"group {name}")
            self.problems.append(
                f"Create {name} in Settings -> Identity and access -> Groups -> Add group -> "
                "Add new, then run this script again."
            )
            return None
        group = found[0]
        kind = group.meta.resource_type if group.meta else None
        if kind == "WorkspaceGroup":
            self.log("wrong", f"group {name} is workspace-local; Unity Catalog can't use it")
            self.problems.append(
                f"Delete the workspace-local {name} (Settings -> Identity and access -> Groups), "
                "recreate it there with Add group -> Add new, then run this script again."
            )
            return None
        self.log("ok", f"group {name} (account group)")
        return group.id

    def ensure_service_principal(self, name: str) -> tuple[str | None, str | None]:
        found = list(self.w.service_principals.list(filter=f'displayName eq "{name}"'))
        if found:
            sp = found[0]
            self.log("ok", f"service principal {name} (application ID {sp.application_id})")
        else:
            self.log("create", f"service principal {name}")
            if self.dry_run:
                return None, None
            sp = self.w.service_principals.create(display_name=name, active=True)
            self.log("note", f"application ID {sp.application_id}: generate its secret in the UI")

        have = {e.value for e in (sp.entitlements or [])}
        missing = [e for e in SP_ENTITLEMENTS if e not in have]
        if missing:
            self.log("update", f"service principal {name} entitlements +{missing}")
            if not self.dry_run:
                self.w.service_principals.patch(
                    sp.id,
                    operations=[
                        iam.Patch(
                            op=iam.PatchOp.ADD,
                            path="entitlements",
                            value=[{"value": e} for e in missing],
                        )
                    ],
                    schemas=PATCH_SCHEMA,
                )
        return sp.id, sp.application_id

    def ensure_members(
        self, group_name: str, group_id: str | None, members: dict[str, str | None]
    ) -> None:
        if group_id is None:  # group missing or unusable: reported already
            return
        current = {m.value for m in (self.w.groups.get(group_id).members or [])}
        # A member with no ID yet is one this dry run would create first.
        missing = {label: mid for label, mid in members.items() if mid not in current}
        for label in members:
            self.log("add" if label in missing else "ok", f"{label} in {group_name}")
        missing = {label: mid for label, mid in missing.items() if mid is not None}
        if missing and not self.dry_run:
            try:
                self.w.groups.patch(
                    group_id,
                    operations=[
                        iam.Patch(
                            op=iam.PatchOp.ADD,
                            path="members",
                            value=[{"value": mid} for mid in missing.values()],
                        )
                    ],
                    schemas=PATCH_SCHEMA,
                )
            except DatabricksError as e:
                self.problems.append(
                    f"Couldn't add {', '.join(missing)} to {group_name} ({e}). Add them in "
                    f"Settings -> Identity and access -> Groups -> {group_name} -> Members."
                )

    def ensure_catalog_grant(self, catalog_name: str, principal: str) -> None:
        """ALL PRIVILEGES on the catalog, inherited by every schema, table and Volume in it.

        Owning a catalog lets a group manage it, but reading inside a schema that
        someone else owns still needs USE SCHEMA, SELECT, READ VOLUME and so on.
        """
        current = self.w.grants.get("catalog", catalog_name, principal=principal)
        have = {
            p.value if hasattr(p, "value") else str(p)
            for a in (current.privilege_assignments or [])
            if a.principal == principal
            for p in (a.privileges or [])
        }
        if catalog.Privilege.ALL_PRIVILEGES.value in have:
            self.log("ok", f"catalog {catalog_name}: {principal} has ALL PRIVILEGES")
            return
        self.log("grant", f"ALL PRIVILEGES on catalog {catalog_name} to {principal}")
        if not self.dry_run:
            self.w.grants.update(
                "catalog",
                catalog_name,
                changes=[
                    catalog.PermissionsChange(
                        add=[catalog.Privilege.ALL_PRIVILEGES], principal=principal
                    )
                ],
            )

    def ensure_catalog_owner(self, catalog_name: str, owner: str) -> None:
        try:
            info = self.w.catalogs.get(catalog_name)
        except NotFound:
            self.log("skip", f"catalog {catalog_name} missing: run bootstrap/00_catalogs.sql")
            return
        self.ensure_catalog_grant(catalog_name, owner)
        if info.owner == owner:
            self.log("ok", f"catalog {catalog_name} owned by {owner}")
            return
        self.log("update", f"catalog {catalog_name} owner {info.owner} -> {owner}")
        if not self.dry_run:
            self.w.catalogs.update(catalog_name, owner=owner)

    def run(self) -> None:
        me = self.w.current_user.me()
        print(f"Workspace {self.w.config.host} as {me.user_name}\n")

        group_ids = {name: self.check_group(name) for name in GROUPS}
        sp_id, _ = self.ensure_service_principal(SERVICE_PRINCIPAL)

        admins = {f"user {me.user_name}": me.id, f"service principal {SERVICE_PRINCIPAL}": sp_id}
        self.ensure_members(ADMINS, group_ids[ADMINS], admins)

        # Ownership last: it needs the account group, and you must still be an owner now.
        if group_ids[ADMINS] is None:
            self.log("skip", f"catalog ownership: {ADMINS} isn't a usable account group yet")
        else:
            for catalog_name in CATALOGS:
                self.ensure_catalog_owner(catalog_name, ADMINS)

        if self.problems:
            print("\nTo do by hand:")
            for problem in self.problems:
                print(f"  - {problem}")
            raise SystemExit(1)
        print("\nAll in place.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", default="courtiq", help="Databricks CLI profile")
    parser.add_argument("--dry-run", action="store_true", help="show changes, make none")
    args = parser.parse_args()
    Bootstrap(WorkspaceClient(profile=args.profile), dry_run=args.dry_run).run()


if __name__ == "__main__":
    main()
